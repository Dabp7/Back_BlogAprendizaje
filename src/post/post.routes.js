import {Router} from 'express';
import {addPost,getPosts,updatePost,deletePost} from './post.controller.js';
import {createPostValidator,updatePostValidator,deletePostValidator} from '../middlewares/post-validators.js';
import {requireAdmin} from '../middlewares/admin.js';
const router=Router();
router.get('/',getPosts);
router.post('/addPost',requireAdmin,createPostValidator,addPost);
router.put('/editPost/:idPost',requireAdmin,updatePostValidator,updatePost);
router.delete('/deletePost/:idPost',requireAdmin,deletePostValidator,deletePost);
export default router;
